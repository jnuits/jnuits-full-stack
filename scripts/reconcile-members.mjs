import process from "node:process";
import {
  buildSupabaseAdminClient,
  getInvitationExpiryIso,
  getNextInvitation,
  parseCliArgs,
  persistOperatorReport,
  resolveMembershipReportPath,
  writeJsonReport,
} from "./lib/members.mjs";

function assertQuerySuccess(label, result) {
  if (result.error) {
    throw new Error(`${label}: ${result.error.message}`);
  }
}

async function main() {
  const args = parseCliArgs(process.argv.slice(2));
  const admin = buildSupabaseAdminClient();
  const nowIso = new Date().toISOString();
  const today = nowIso.slice(0, 10);

  const [
    approvedApplicationsResult,
    activeExpiredInvitationsResult,
    inactiveInvitationsResult,
    activeTermsResult,
    activeAssignmentsResult,
  ] = await Promise.all([
    admin
      .from("membership_applications")
      .select("id, name, email, processed_member_id, invitation_id, status")
      .eq("status", "approved")
      .not("processed_member_id", "is", null)
      .is("invitation_id", null),
    admin
      .from("member_invitations")
      .select("id, member_id, expires_at, is_active, revoked_at")
      .eq("is_active", true)
      .lt("expires_at", nowIso),
    admin
      .from("member_invitations")
      .select("id, member_id, expires_at, is_active, revoked_at")
      .eq("is_active", false)
      .is("revoked_at", null),
    admin
      .from("committee_terms")
      .select("id, title, slug, ends_on, status")
      .eq("status", "active")
      .lt("ends_on", today),
    admin
      .from("committee_assignments")
      .select("id, term_id, ends_on, status")
      .eq("status", "active")
      .lt("ends_on", today),
  ]);

  assertQuerySuccess("membership_applications query failed", approvedApplicationsResult);
  assertQuerySuccess(
    "active expired invitations query failed",
    activeExpiredInvitationsResult
  );
  assertQuerySuccess(
    "inactive invitations query failed",
    inactiveInvitationsResult
  );
  assertQuerySuccess("active committee terms query failed", activeTermsResult);
  assertQuerySuccess(
    "active committee assignments query failed",
    activeAssignmentsResult
  );

  const fixes = {
    archivedTerms: 0,
    completedAssignments: 0,
    failedWrites: 0,
    generatedInvitations: 0,
    markedExpiredInvitations: 0,
    repairedRevokedTimestamps: 0,
  };

  const rows = [];

  for (const application of approvedApplicationsResult.data || []) {
    let invitationCode = null;
    let failure = null;

    if (args.apply && application.processed_member_id) {
      const nextInvitation = await getNextInvitation(admin);
      const expiresAt = getInvitationExpiryIso(args.expiryDays);

      const { data: invitation, error: invitationError } = await admin
        .from("member_invitations")
        .insert({
          code_hash: nextInvitation.codeHash,
          expires_at: expiresAt,
          max_uses: args.maxUses,
          member_id: application.processed_member_id,
          notes: "Generated by membership reconciliation",
        })
        .select("id")
        .single();

      if (!invitationError && invitation) {
        const { error: applicationUpdateError } = await admin
          .from("membership_applications")
          .update({
            invitation_id: invitation.id,
          })
          .eq("id", application.id);

        if (!applicationUpdateError) {
          invitationCode = nextInvitation.code;
          fixes.generatedInvitations += 1;
        } else {
          failure = applicationUpdateError.message;
          fixes.failedWrites += 1;
        }
      } else {
        failure = invitationError?.message || "Invitation insert failed";
        fixes.failedWrites += 1;
      }
    }

    rows.push({
      action: "approved_without_invitation",
      applicationId: application.id,
      invitationCode,
      memberId: application.processed_member_id,
      mode: args.apply ? "apply" : "dry-run",
      name: application.name,
      writeFailure: failure,
    });
  }

  for (const invitation of activeExpiredInvitationsResult.data || []) {
    let failure = null;

    if (args.apply) {
      const { error } = await admin
        .from("member_invitations")
        .update({
          is_active: false,
          revoked_at: nowIso,
        })
        .eq("id", invitation.id);

      if (!error) {
        fixes.markedExpiredInvitations += 1;
      } else {
        failure = error.message;
        fixes.failedWrites += 1;
      }
    }

    rows.push({
      action: "active_expired_invitation",
      invitationId: invitation.id,
      memberId: invitation.member_id,
      mode: args.apply ? "apply" : "dry-run",
      writeFailure: failure,
    });
  }

  for (const invitation of inactiveInvitationsResult.data || []) {
    let failure = null;

    if (args.apply) {
      const { error } = await admin
        .from("member_invitations")
        .update({
          revoked_at: nowIso,
        })
        .eq("id", invitation.id);

      if (!error) {
        fixes.repairedRevokedTimestamps += 1;
      } else {
        failure = error.message;
        fixes.failedWrites += 1;
      }
    }

    rows.push({
      action: "inactive_invitation_missing_revoked_at",
      invitationId: invitation.id,
      memberId: invitation.member_id,
      mode: args.apply ? "apply" : "dry-run",
      writeFailure: failure,
    });
  }

  for (const term of activeTermsResult.data || []) {
    let failure = null;

    if (args.apply) {
      const { error } = await admin
        .from("committee_terms")
        .update({
          status: "archived",
        })
        .eq("id", term.id);

      if (!error) {
        fixes.archivedTerms += 1;
      } else {
        failure = error.message;
        fixes.failedWrites += 1;
      }
    }

    rows.push({
      action: "active_term_past_end_date",
      mode: args.apply ? "apply" : "dry-run",
      slug: term.slug,
      termId: term.id,
      title: term.title,
      writeFailure: failure,
    });
  }

  for (const assignment of activeAssignmentsResult.data || []) {
    let failure = null;

    if (args.apply) {
      const { error } = await admin
        .from("committee_assignments")
        .update({
          status: "completed",
        })
        .eq("id", assignment.id);

      if (!error) {
        fixes.completedAssignments += 1;
      } else {
        failure = error.message;
        fixes.failedWrites += 1;
      }
    }

    rows.push({
      action: "active_assignment_past_end_date",
      assignmentId: assignment.id,
      mode: args.apply ? "apply" : "dry-run",
      termId: assignment.term_id,
      writeFailure: failure,
    });
  }

  const report = {
    generatedAt: new Date().toISOString(),
    mode: args.apply ? "apply" : "dry-run",
    summary: {
      approvedWithoutInvitation: (approvedApplicationsResult.data || []).length,
      fixes,
      inactiveInvitationsMissingRevokedAt:
        (inactiveInvitationsResult.data || []).length,
      staleActiveAssignments: (activeAssignmentsResult.data || []).length,
      staleActiveTerms: (activeTermsResult.data || []).length,
      totalFindings: rows.length,
    },
    rows,
  };

  const reportPath = resolveMembershipReportPath(
    "membership-reconciliation",
    args.report
  );
  writeJsonReport(reportPath, report);

  if (args.persistReport) {
    await persistOperatorReport(admin, {
      report,
      reportType: "membership_reconciliation",
      summary: `Membership reconciliation ${args.apply ? "apply" : "dry-run"} with ${rows.length} findings and ${fixes.failedWrites} failed writes.`,
      title: `Membership reconciliation ${args.apply ? "apply" : "dry-run"}`,
    });
  }

  console.log(
    JSON.stringify(
      {
        mode: args.apply ? "apply" : "dry-run",
        reportPath,
        summary: report.summary,
      },
      null,
      2
    )
  );
}

main().catch((error) => {
  console.error(
    JSON.stringify(
      {
        error:
          error instanceof Error ? error.message : "Unknown reconciliation error",
      },
      null,
      2
    )
  );
  process.exitCode = 1;
});
